    /**
     * 生成随机用户
     * @param nameLen 名字长度（1或2，常用中文名），传0表示随机1~2
     */
    public static User randomUser(int nameLen) {
        String surname = SURNAMES[RND.nextInt(SURNAMES.length)];
        if (nameLen <= 0) nameLen = RND.nextBoolean() ? 1 : 2;

        StringBuilder given = new StringBuilder();
        for (int i = 0; i < nameLen; i++) {
            given.append(NAME_CHARS[RND.nextInt(NAME_CHARS.length)]);
        }

        String name = surname + given;
        String id = UUID.randomUUID().toString().replace("-", "").substring(0, 12);
        String email = randomPinyinEmail() + "@" + randomDomain();
        int age = RND.nextInt(18, 61);

        return new User(id, name, email, age);
    }

    public static User randomUser() {
        return randomUser(0);
    }

    /** 生成指定数量的随机用户（ID 去重） */
    public static List<User> randomUsers(int count) {
        Set<String> ids = new HashSet<>();
        List<User> result = new ArrayList<>(count);
        while (result.size() < count) {
            User u = randomUser(0);
            if (ids.add(u.getId())) {
                result.add(u);
            }
        }
        return result;
    }

